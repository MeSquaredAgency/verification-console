// Writes apps/api/migrations/0002_demo_seed.sql from fixtures/data.ts: the fictional demo client,
// its playbooks and reference records, and the first admin. Phase 0 runs on fixture data only.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DEMO_CLIENT, DEMO_PLAYBOOK, DEMO_REFERENCE } from "../fixtures/data";

const FIRST_ADMIN = { email: "elliot.crabb@mesquaredagency.com", name: "Elliot Crabb" };
const q = (v: string | number | null) => (v == null ? "NULL" : typeof v === "number" ? String(v) : `'${v.replace(/'/g, "''")}'`);
const ts = "2026-10-23T00:00:00.000Z";
const c = DEMO_CLIENT;
const lines = [
  "-- Generated by scripts/gen-seed-sql.ts. Fictional demo data for Phase 0, plus the first admin.",
  `INSERT INTO clients (id, name, tier3_threshold_cents, seeded_rate, retention_days, flags_json) VALUES (${q(c.id)}, ${q(c.name)}, ${c.tier3_threshold_cents}, ${c.seeded_rate}, ${c.retention_days}, '{}');`,
  `INSERT INTO users (email, name, role, licensed_apn) VALUES (${q(FIRST_ADMIN.email)}, ${q(FIRST_ADMIN.name)}, 'admin', 0);`,
];
for (const type of ["supplier_bill", "tenant_email"]) {
  lines.push(`INSERT INTO playbooks (id, client_id, task_type, version, content_json, created_by, created_at) VALUES (${q(`pb_${c.id}_${type}_1`)}, ${q(c.id)}, ${q(type)}, 1, ${q(JSON.stringify(DEMO_PLAYBOOK))}, 'seed', ${q(ts)});`);
}
const rows: [string, string, unknown][] = [
  ...DEMO_REFERENCE.suppliers.map((x) => ["supplier", x.name, x] as [string, string, unknown]),
  ...DEMO_REFERENCE.tenancies.map((x) => ["tenancy", x.tenant_name, x] as [string, string, unknown]),
  ...DEMO_REFERENCE.contacts.map((x) => ["contact", x.email, x] as [string, string, unknown]),
  ...DEMO_REFERENCE.account_codes.map((x) => ["account_code", x.code, x] as [string, string, unknown]),
];
rows.forEach(([kind, key, data], i) => {
  lines.push(`INSERT INTO reference_records (id, client_id, kind, key, data_json, updated_at) VALUES (${q(`ref_${i}`)}, ${q(c.id)}, ${q(kind)}, ${q(key)}, ${q(JSON.stringify(data))}, ${q(ts)});`);
});
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../apps/api/migrations/0002_demo_seed.sql");
writeFileSync(out, lines.join("\n") + "\n");
console.log(`Wrote ${out}`);
