-- Verification Console schema (Cloudflare D1 / SQLite).
-- Timestamps are ISO-8601 UTC strings. JSON columns end in _json.

CREATE TABLE users (
  email TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('operator','senior','admin','auditor')),
  licensed_apn INTEGER NOT NULL DEFAULT 0,
  active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE clients (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  tier3_threshold_cents INTEGER NOT NULL,
  seeded_rate INTEGER NOT NULL DEFAULT 20,       -- 1 in N items gets a seeded test error
  retention_days INTEGER NOT NULL DEFAULT 90,
  spot_check_floor_ms INTEGER,                   -- median ms per claim below which an item is spot-checked; NULL until calibrated
  flags_json TEXT NOT NULL DEFAULT '{}'
);

CREATE TABLE client_assignments (
  client_id TEXT NOT NULL REFERENCES clients(id),
  user_email TEXT NOT NULL REFERENCES users(email),
  PRIMARY KEY (client_id, user_email)
);

CREATE TABLE playbooks (
  id TEXT PRIMARY KEY,
  client_id TEXT NOT NULL REFERENCES clients(id),
  task_type TEXT NOT NULL,
  version INTEGER NOT NULL,
  content_json TEXT NOT NULL,
  created_by TEXT NOT NULL,
  created_at TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  UNIQUE (client_id, task_type, version)
);

CREATE TABLE reference_records (
  id TEXT PRIMARY KEY,
  client_id TEXT NOT NULL REFERENCES clients(id),
  kind TEXT NOT NULL CHECK (kind IN ('supplier','tenancy','contact','account_code')),
  key TEXT NOT NULL,
  data_json TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX idx_reference_client ON reference_records(client_id, kind);

CREATE TABLE tasks (
  id TEXT PRIMARY KEY,
  client_id TEXT NOT NULL REFERENCES clients(id),
  type TEXT NOT NULL CHECK (type IN ('supplier_bill','tenant_email')),
  title TEXT NOT NULL,
  tier INTEGER NOT NULL DEFAULT 1,
  tier_reasons_json TEXT NOT NULL DEFAULT '[]',
  status TEXT NOT NULL,
  stage TEXT,
  error TEXT,
  playbook_id TEXT REFERENCES playbooks(id),
  current_draft_id TEXT,
  redraft_note TEXT,
  needs_licensed_reviewer INTEGER NOT NULL DEFAULT 0,
  lock_holder TEXT,
  lock_expires_at TEXT,
  operator_approved_by TEXT,
  operator_approved_at TEXT,
  created_by TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  queued_at TEXT,
  pipeline_json TEXT              -- intermediate output between pipeline stages
);
CREATE INDEX idx_tasks_status ON tasks(status, client_id);

CREATE TABLE source_documents (
  id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL REFERENCES tasks(id),
  kind TEXT NOT NULL CHECK (kind IN ('pdf','email')),
  filename TEXT,
  content_hash TEXT NOT NULL,
  r2_key TEXT,
  text TEXT NOT NULL,
  layout_json TEXT,
  meta_json TEXT,
  created_at TEXT NOT NULL,
  purged_at TEXT
);

CREATE TABLE facts (
  id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL REFERENCES tasks(id),
  kind TEXT NOT NULL,
  label TEXT NOT NULL,
  value TEXT NOT NULL,
  quote TEXT NOT NULL,
  span_start INTEGER NOT NULL,
  span_end INTEGER NOT NULL
);
CREATE INDEX idx_facts_task ON facts(task_id);

CREATE TABLE drafts (
  id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL REFERENCES tasks(id),
  version INTEGER NOT NULL,
  content_json TEXT NOT NULL,      -- the true draft
  display_json TEXT,               -- seeded copy shown to the operator, NULL when none
  author TEXT NOT NULL,            -- 'model' or an operator email
  model TEXT,
  prompt_version TEXT,
  parent_id TEXT,
  created_at TEXT NOT NULL,
  UNIQUE (task_id, version)
);

CREATE TABLE claims (
  id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL REFERENCES tasks(id),
  draft_id TEXT NOT NULL REFERENCES drafts(id),
  ord INTEGER NOT NULL,
  claim_key TEXT NOT NULL,         -- identity across draft versions
  type TEXT NOT NULL,
  label TEXT NOT NULL,
  field TEXT,                      -- bill field; NULL for reply text
  value_true TEXT NOT NULL,
  value_display TEXT NOT NULL,
  start INTEGER,                   -- span in the displayed reply body
  end INTEGER,
  true_start INTEGER,              -- span in the true reply body
  true_end INTEGER,
  source_value TEXT,
  source_start INTEGER,
  source_end INTEGER,
  checks_json TEXT NOT NULL DEFAULT '[]',
  model_verdict TEXT,
  group_name TEXT NOT NULL,
  needs_rekey INTEGER NOT NULL DEFAULT 0,
  rekeyed INTEGER NOT NULL DEFAULT 0,
  rekey_mismatch INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'undecided',
  prev_claim_id TEXT,              -- same claim in the previous draft version, if carried over
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX idx_claims_draft ON claims(draft_id);

CREATE TABLE decisions (
  id TEXT PRIMARY KEY,             -- generated by the client so retries are idempotent
  task_id TEXT NOT NULL REFERENCES tasks(id),
  claim_id TEXT NOT NULL REFERENCES claims(id),
  actor TEXT NOT NULL,
  role TEXT NOT NULL,
  action TEXT NOT NULL CHECK (action IN ('confirm','correct','flag','rekey')),
  value TEXT,                      -- re-keyed value or correction
  note TEXT,
  outcome TEXT,                    -- e.g. 'match', 'mismatch', 'canary_caught'
  time_ms INTEGER,
  created_at TEXT NOT NULL
);
CREATE INDEX idx_decisions_task ON decisions(task_id);

CREATE TABLE canaries (
  id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL REFERENCES tasks(id),
  draft_id TEXT NOT NULL,
  claim_id TEXT NOT NULL,
  label TEXT NOT NULL,
  original_value TEXT NOT NULL,
  seeded_value TEXT NOT NULL,
  operator TEXT,
  outcome TEXT NOT NULL DEFAULT 'pending' CHECK (outcome IN ('pending','caught','missed','void')),
  created_at TEXT NOT NULL,
  resolved_at TEXT
);
CREATE INDEX idx_canaries_task ON canaries(task_id);

CREATE TABLE releases (
  id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL REFERENCES tasks(id),
  draft_id TEXT NOT NULL,
  output_json TEXT NOT NULL,
  output_hash TEXT NOT NULL,
  destination TEXT NOT NULL,       -- Phase 0: 'database'
  external_id TEXT,                -- e.g. Gmail message id in later phases
  approved_by TEXT NOT NULL,
  second_reviewer TEXT,
  created_at TEXT NOT NULL
);

CREATE TABLE incidents (
  id TEXT PRIMARY KEY,
  release_id TEXT NOT NULL REFERENCES releases(id),
  task_id TEXT NOT NULL,
  reported_by TEXT NOT NULL,
  report TEXT NOT NULL,
  claim_ids_json TEXT NOT NULL DEFAULT '[]',
  root_cause TEXT CHECK (root_cause IN ('source','extraction','drafting','check','operator')),
  fix TEXT,
  status TEXT NOT NULL DEFAULT 'open',
  created_at TEXT NOT NULL,
  closed_at TEXT
);

CREATE TABLE model_calls (
  id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL,
  stage TEXT NOT NULL,
  mode TEXT NOT NULL,              -- 'anthropic' or 'offline'
  model TEXT NOT NULL,
  prompt_version TEXT NOT NULL,
  input_hash TEXT NOT NULL,
  output_json TEXT NOT NULL,
  duration_ms INTEGER NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE spot_checks (
  id TEXT PRIMARY KEY,
  task_id TEXT NOT NULL,
  operator TEXT NOT NULL,
  reason TEXT NOT NULL,
  median_ms INTEGER,
  created_at TEXT NOT NULL,
  reviewed_by TEXT,
  reviewed_at TEXT
);

CREATE TABLE activity (
  email TEXT PRIMARY KEY,
  streak_start TEXT NOT NULL,
  last_at TEXT NOT NULL,
  last_task_type TEXT
);

-- Append-only log of every view, decision, edit and release.
CREATE TABLE audit_events (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  ts TEXT NOT NULL,
  actor TEXT NOT NULL,
  task_id TEXT,
  event TEXT NOT NULL,
  detail_json TEXT NOT NULL DEFAULT '{}'
);
CREATE INDEX idx_audit_task ON audit_events(task_id);
CREATE TRIGGER audit_events_no_update BEFORE UPDATE ON audit_events
BEGIN SELECT RAISE(ABORT, 'audit_events is append-only'); END;
CREATE TRIGGER audit_events_no_delete BEFORE DELETE ON audit_events
BEGIN SELECT RAISE(ABORT, 'audit_events is append-only'); END;
